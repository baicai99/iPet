import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const repoRoot = path.resolve(__dirname, '..', '..')

const TOKENS_PATH = path.join(repoRoot, 'src', 'design', 'tokens.json')
const THEME_VARS_SCSS_PATH = path.join(repoRoot, 'src', 'styles', 'theme-variables.scss')
const GENERATED_STYLES_DIR = path.join(repoRoot, 'src', 'styles', 'generated')
const TOKENS_SCSS_PATH = path.join(GENERATED_STYLES_DIR, 'tokens.scss')
const TYPOGRAPHY_MIXINS_SCSS_PATH = path.join(GENERATED_STYLES_DIR, 'typography.mixins.scss')

const readJson = async (filePath) => {
    const raw = await fs.readFile(filePath, 'utf8')
    try {
        return JSON.parse(raw)
    } catch (error) {
        throw new Error(`[tokens] Failed to parse JSON: ${filePath}\n${error instanceof Error ? error.message : String(error)}`)
    }
}

const requireObject = (value, label) => {
    if (!value || typeof value !== 'object' || Array.isArray(value)) {
        throw new Error(`[tokens] Expected object at ${label}`)
    }
    return value
}

const requireString = (value, label) => {
    if (typeof value !== 'string' || !value.trim()) {
        throw new Error(`[tokens] Expected non-empty string at ${label}`)
    }
    return value
}

const requireNumber = (value, label) => {
    if (typeof value !== 'number' || Number.isNaN(value)) {
        throw new Error(`[tokens] Expected number at ${label}`)
    }
    return value
}

const toKebabCase = (input) =>
    String(input)
        .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
        .replace(/_/g, '-')
        .toLowerCase()

const formatScssVarBlock = (vars, indent = '    ') =>
    Object.entries(vars)
        .map(([name, value]) => `${indent}${name}: ${value};`)
        .join('\n')

const main = async () => {
    const tokens = await readJson(TOKENS_PATH)

    const colors = requireObject(tokens.colors, 'colors')
    const semantic = requireObject(colors.semantic, 'colors.semantic')

    const typography = requireObject(tokens.typography, 'typography')

    // ---------------------------------------------------------------------
    // theme-variables.scss
    // ---------------------------------------------------------------------

    const cssVars = {
        '--app-bg-primary': requireString(semantic.bgPrimary, 'colors.semantic.bgPrimary'),
        '--app-bg-card': requireString(semantic.bgCard, 'colors.semantic.bgCard'),
        '--app-bg-navbar': requireString(semantic.bgNavbar, 'colors.semantic.bgNavbar'),

        '--app-border-color': requireString(semantic.borderColor, 'colors.semantic.borderColor'),

        '--app-text-primary': requireString(semantic.textPrimary, 'colors.semantic.textPrimary'),
        '--app-text-secondary': requireString(semantic.textSecondary, 'colors.semantic.textSecondary'),
        '--app-text-muted': requireString(semantic.textMuted, 'colors.semantic.textMuted'),
        '--app-text-disabled': requireString(semantic.textDisabled, 'colors.semantic.textDisabled'),

        '--app-danger-color': requireString(semantic.dangerColor, 'colors.semantic.dangerColor'),
        '--app-danger-border': requireString(semantic.dangerBorder, 'colors.semantic.dangerBorder'),
        '--app-danger-bg-active': requireString(semantic.dangerBgActive, 'colors.semantic.dangerBgActive'),

        '--app-active-bg': requireString(semantic.activeBg, 'colors.semantic.activeBg')
    }

    const legacyAliases = {
        '--app-background': 'var(--app-bg-primary)',
        '--app-card-bg': 'var(--app-bg-card)',
        '--app-navbar-bg': 'var(--app-bg-navbar)'
    }

    const themeVarsScss = [
        '// ============================================================================',
        '// Global Theme Variables (Generated)',
        '// ============================================================================',
        `// Source of truth: src/design/tokens.json`,
        '// DO NOT EDIT THIS FILE DIRECTLY. Run: npm run tokens:build',
        '',
        ':root {',
        '    // Canonical semantic tokens',
        formatScssVarBlock(cssVars),
        '',
        '    // Legacy aliases (migration)',
        formatScssVarBlock(legacyAliases),
        '}',
        ''
    ].join('\n')

    await fs.writeFile(THEME_VARS_SCSS_PATH, themeVarsScss, 'utf8')

    // ---------------------------------------------------------------------
    // tokens.scss (SCSS variables for non-CSS-var platforms / fallbacks)
    // ---------------------------------------------------------------------

    const scssVars = Object.fromEntries(
        Object.entries(cssVars).map(([cssVarName, value]) => [`$${cssVarName.replace(/^--/, '')}`, value])
    )

    const scssLegacyAliases = {
        '$app-background': '$app-bg-primary',
        '$app-card-bg': '$app-bg-card',
        '$app-navbar-bg': '$app-bg-navbar'
    }

    const tokensScss = [
        '// ============================================================================',
        '// App Tokens (Generated)',
        '// ============================================================================',
        `// Source of truth: src/design/tokens.json`,
        '// DO NOT EDIT THIS FILE DIRECTLY. Run: npm run tokens:build',
        '',
        formatScssVarBlock(scssVars, ''),
        '',
        '// Legacy aliases (migration)',
        ...Object.entries(scssLegacyAliases).map(([name, aliasTo]) => `${name}: ${aliasTo};`),
        ''
    ].join('\n')

    await fs.mkdir(GENERATED_STYLES_DIR, { recursive: true })
    await fs.writeFile(TOKENS_SCSS_PATH, tokensScss, 'utf8')

    // ---------------------------------------------------------------------
    // typography mixins
    // ---------------------------------------------------------------------

    const mixinOrder = [
        ['largeTitle', 'text-large-title'],
        ['title2', 'text-title-2'],
        ['headline', 'text-headline'],
        ['body', 'text-body'],
        ['subhead', 'text-subhead'],
        ['caption1', 'text-caption-1'],
        ['caption2', 'text-caption-2']
    ]

    const mixinBlocks = mixinOrder.map(([tokenKey, mixinName]) => {
        const style = requireObject(typography[tokenKey], `typography.${tokenKey}`)
        const fontSizeRpx = requireNumber(style.fontSizeRpx, `typography.${tokenKey}.fontSizeRpx`)
        const fontWeight = requireNumber(style.fontWeight, `typography.${tokenKey}.fontWeight`)
        const lineHeight = requireNumber(style.lineHeight, `typography.${tokenKey}.lineHeight`)

        return [
            `@mixin ${mixinName} {`,
            `    font-size: ${fontSizeRpx}rpx;`,
            `    font-weight: ${fontWeight};`,
            `    line-height: ${lineHeight};`,
            '}',
            ''
        ].join('\n')
    })

    const typographyMixinsScss = [
        '// ============================================================================',
        '// Typography Mixins (Generated)',
        '// ============================================================================',
        `// Source of truth: src/design/tokens.json`,
        '// DO NOT EDIT THIS FILE DIRECTLY. Run: npm run tokens:build',
        '',
        ...mixinBlocks
    ].join('\n')

    await fs.writeFile(TYPOGRAPHY_MIXINS_SCSS_PATH, typographyMixinsScss, 'utf8')

    // ---------------------------------------------------------------------
    // Done
    // ---------------------------------------------------------------------

    const touched = [
        path.relative(repoRoot, THEME_VARS_SCSS_PATH),
        path.relative(repoRoot, TOKENS_SCSS_PATH),
        path.relative(repoRoot, TYPOGRAPHY_MIXINS_SCSS_PATH)
    ]

    // eslint-disable-next-line no-console
    console.log(`[tokens] Wrote ${touched.join(', ')}`)
}

main().catch((error) => {
    // eslint-disable-next-line no-console
    console.error(error)
    process.exitCode = 1
})
