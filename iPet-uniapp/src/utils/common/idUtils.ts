/**
 * Ensures that an ID is returned as a string.
 * Handles numbers and strings. Returns empty string if input is null/undefined.
 */
export const ensureStringId = (id: string | number | null | undefined): string => {
    if (id === null || id === undefined) {
        return ''
    }
    return String(id)
}

/**
 * Generates a temporary ID with a specific prefix.
 * Format: prefix_timestamp_random
 */
export const generateTempId = (prefix: string = 'temp'): string => {
    const timestamp = Date.now()
    const random = Math.random().toString(36).substring(2, 9)
    return `${prefix}_${timestamp}_${random}`
}

/**
 * Checks if an ID is a temporary ID generated by the frontend.
 */
export const isTempId = (id: string): boolean => {
    return id.startsWith('temp_')
}
